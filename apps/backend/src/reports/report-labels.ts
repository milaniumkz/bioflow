export function reportValue(value: unknown): string {
  if (typeof value === "boolean") return value ? "Да" : "Нет";
  const text = value == null ? "—" : String(value);
  if (Object.hasOwn(reportLabels, text)) return reportLabels[text];
  return text
    .replace(
      /(?:[a-z0-9]{20,}-)?\b(LOT|WB|PROC|OP)-(\d+)\b/g,
      (_all, kind, digits) =>
        `${({ LOT: "Партия", WB: "Рейс", PROC: "Обработка", OP: "Операция" } as Record<string, string>)[kind]} №${Number(digits)}`,
    )
    .replace(/\bc[a-z0-9]{20,}\b/gi, "связанная запись")
    .replace(/\b[0-9a-f]{8}-[0-9a-f-]{27,}\b/gi, "связанная запись");
}
export function localizeReport(rows: Record<string, unknown>[]) {
  return rows.map((row) => {
    const output: Record<string, unknown> = {};
    let other = 0;
    for (const [key, value] of Object.entries(row)) {
      const last = key.split(".").at(-1)!;
      const internal =
        /(^|\.)(id|.*Id|.*Ids|.*Hash|.*Token|idempotencyKey|passwordHash)$/.test(
          key,
        );
      if (internal && value !== "[скрыто]") continue;
      const label = internal
        ? "Защищённые данные"
        : ((Object.hasOwn(reportLabels, key) ? reportLabels[key] : undefined) ??
          (Object.hasOwn(reportLabels, last)
            ? reportLabels[last]
            : undefined) ??
          (/[А-Яа-яЁё]/.test(key) ? key : `Сведения ${++other}`));
      let heading = label,
        duplicate = 1;
      while (heading in output) heading = `${label} (${++duplicate})`;
      if (/Date$/.test(last) && /^\d{4}-\d{2}-\d{2}$/.test(String(value))) {
        output[heading] = new Date(
          String(value) + "T12:00:00Z",
        ).toLocaleDateString("ru-RU", { timeZone: "UTC" });
        continue;
      }
      output[heading] =
        /(?:At|Date)$/.test(last) &&
        value &&
        Number.isFinite(Date.parse(String(value)))
          ? new Date(String(value)).toLocaleString("ru-RU", {
              timeZone: "Asia/Yekaterinburg",
            })
          : reportValue(value);
    }
    return output;
  });
}

export function reportFilename(type: string, format: string) {
  const extension = ["csv", "xlsx", "pdf"].includes(format) ? format : "csv";
  return `attachment; filename="report.${extension}"; filename*=UTF-8''${encodeURIComponent(`Отчёт-${reportTitles[type] ?? "Данные"}`)}.${extension}`;
}
