export const businessLabels: Record<string, string> = new Proxy(translations, {
  get(target, key) {
    if (typeof key !== "string") return Reflect.get(target, key);
    return Object.prototype.hasOwnProperty.call(target, key)
      ? target[key]
      : /[А-Яа-яЁё]/.test(key)
        ? key
        : "Операция учёта";
  },
});
export function caption(key: string) {
  return Object.hasOwn(translations, key) ? translations[key] : "Сведения";
}
export function visibleText(value: unknown): string {
  const text = String(value ?? "—");
  if (Object.hasOwn(translations, text)) return translations[text];
  if (/^(c[a-z0-9]{20,}|[0-9a-f]{8}-[0-9a-f-]{27,})$/i.test(text))
    return "Связанная запись";
  if (/^Process\s+/.test(text)) return "Обработка партии";
  if (/^[A-Z]+(?:_[A-Z0-9]+)+$/.test(text)) return "Операция учёта";
  return recordLabel(text).replace(/\bc[a-z0-9]{20,}\b/gi, "указанная запись");
}
